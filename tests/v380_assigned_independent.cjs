const fs = require('fs');
const path = require('path');
const assert = require('assert');
const root = path.join(__dirname,'..');
const page = fs.readFileSync(path.join(root,'assigned-request.html'),'utf8');
const app = fs.readFileSync(path.join(root,'assets/app.js'),'utf8');
const index = fs.readFileSync(path.join(root,'index.html'),'utf8');
const route = fs.readFileSync(path.join(root,'assets/route-guard.js'),'utf8');
const headers = fs.readFileSync(path.join(root,'_headers'),'utf8');
const middleware = fs.readFileSync(path.join(root,'functions/_middleware.js'),'utf8');
const apiCache=fs.readFileSync(path.join(root,'api-cache.js'),'utf8');
const music=fs.readFileSync(path.join(root,'assets/music-shell.js'),'utf8');
assert.match(index, /href="'\/assigned-request\.html\?id='\+encodeURIComponent\(task\.id\)"/);
assert(!index.includes('class="assigned-request-form"'), 'student form must not remain inline on homepage');
assert(index.includes('搜索管理员发放的申请'));
assert(page.includes('data-page="assigned-request"'));
assert(page.includes('assignedPageApi.submit()'));
for(const field of ['activityName','participants','location','activityTime','images','attachment'])assert(page.includes('assignedPageForm.'+field));
assert(app.includes('assignedPageApi:{}'));
assert(app.includes("'assigned-request','admin'"));
assert(route.includes("'/assigned-request.html'"));
assert(headers.includes('Cache-Control: no-store'));
assert(middleware.includes("headers.set('Cache-Control', 'no-store, max-age=0')"));
assert(apiCache.includes('const DEFAULT_TTL = 30000'));
assert(music.includes('caches.open(CACHE)'), 'music audio cache must remain');
console.log('PASS independent Vue3 task page, card navigation, required form fields, private API responses and session cache policy and preserved music cache');
